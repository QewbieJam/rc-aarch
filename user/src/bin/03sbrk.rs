#![no_std]
#![no_main]

//! app_3：验证 sbrk（ch4）—— 对照 rCore ch4 的 `user/src/bin/sbrk_test.rs`
//!
//! ## 这个测试在验什么
//!
//! 分页之后，`sbrk` 是用户程序“向内核要新页”的唯一手段：内核在 program_brk
//! 处向后追加虚拟页（背后是新分配的物理页帧）。
//!
//! 期望的三步：
//!   1. 初始 brk = 用户栈顶（本例 0x17000 附近）；
//!   2. `sbrk(4096)` 返回旧 brk，新页首尾都能读写；
//!   3. `sbrk(8192)` 再扩两页，跨页写也不能炸；缩太狠应失败返回 -1。
//!
//! ## 测试设计方法
//! - **边界值**：0 / +4096（一页）/ +8192（两页）/ -0x100000（非法缩回）；
//! - **边界点**：每个新页的**首字节和末字节**（最容易踩到页边界的地方）；
//! - **错误路径**：缩到 heap_bottom 以下必须返回 -1。
//!
//! ## 怎么看结果
//! - 通过：打印 `[app3] 跨页读写 OK ✓` 等，退出码 0；
//! - 失败：`assert_eq!` 触发 panic → 非 0 退出。

#[macro_use]
extern crate user_lib;

use user_lib::sbrk;

#[unsafe(no_mangle)]
fn main() -> i32 {
    // =====================================================================
    // 0) 基线：先看当前 program break 在哪
    // =====================================================================
    let old = sbrk(0); // sbrk(0) 不扩也不缩，只返回当前 brk
    println!("[app3] sbrk_test: 初始 brk = {:#x}", old as usize);

    // =====================================================================
    // ① 扩一页（边界值 +4096），并测新页的首、末字节
    // =====================================================================
    // Act：扩 4096 字节；按约定返回“旧的 brk”（也就是新页的起始地址）。
    let p1 = sbrk(4096);
    println!("[app3] sbrk(4096) -> {:#x}", p1 as usize);
    // Assert：返回的必须是旧 brk。
    assert_eq!(p1, old, "sbrk 应该返回旧的 brk");
    unsafe {
        let p = p1 as *mut u8;
        // 页首写 0xAB、页末写 0xCD（边界值最容易被漏掉的两个地址）。
        p.write_volatile(0xAB);
        p.add(4095).write_volatile(0xCD);
        // Assert：两个位置都能原样读回，说明新页真的映射好了。
        assert_eq!(p.read_volatile(), 0xAB);
        assert_eq!(p.add(4095).read_volatile(), 0xCD);
    }
    println!("[app3] 新页可读可写 ✓");

    // =====================================================================
    // ② 再扩两页（边界值 +8192），写到第二页末尾（跨页）
    // =====================================================================
    // Act：再扩 8192 字节（两页）。
    let p2 = sbrk(8192);
    println!("[app3] sbrk(8192) -> {:#x}", p2 as usize);
    unsafe {
        let p = p2 as *mut u8;
        // 写到第二页的最后一个字节（p + 8191）——跨页写是否正确的关键点。
        p.add(8191).write_volatile(0x5A);
        // Assert：能原样读回，说明两页都映射到了不同的物理页。
        assert_eq!(p.add(8191).read_volatile(), 0x5A);
    }
    println!("[app3] 跨页读写 OK ✓");

    // =====================================================================
    // ③ 错误路径：缩得太多（-0x100000）必须失败
    // =====================================================================
    // Act：一次缩 1MB，远小于当前堆的大小。
    let bad = sbrk(-0x100000);
    // Assert：内核应拒绝，返回 -1（不能把堆缩到 heap_bottom 以下）。
    println!("[app3] sbrk(-0x100000) = {}（-1 表示失败，符合预期）", bad);
    assert_eq!(bad, -1);
    0
}
